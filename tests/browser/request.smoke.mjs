import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { chromium, expect } from '@playwright/test';

const base = process.env.OSCAR_BASE_URL || 'https://localhost:4201';
if (!['localhost', '127.0.0.1', '[::1]'].includes(new URL(base).hostname)) throw new Error('Teste somente no localhost.');
const executablePath = process.env.OSCAR_BROWSER || process.env.LOCALAPPDATA + '/ms-playwright/chromium-1243/chrome-win64/chrome.exe';
const browser = await chromium.launch({ headless: true, ...(existsSync(executablePath) ? { executablePath } : {}) });
const context = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const output = resolve('tests/results/request-' + Date.now());
await mkdir(output, { recursive: true });
const name = 'Cliente Teste Solicitação';
const symptoms = 'Motor perde potência e acende luz de injeção ao acelerar.';
try {
 await page.goto(base + '/catalogo');
 await expect(page.getByRole('heading', { name: 'Serviços da oficina' })).toBeVisible();
 await page.getByRole('navigation', { name: 'Navegação do catálogo' }).getByRole('link', { name: 'Serviços' }).click();
 await expect(page).toHaveURL(/\/catalogo#servicos$/);
 await page.locator('.hero-scheduling').click();
 await expect(page).toHaveURL(/#solicitar-atendimento$/);
 await expect(page.locator('.workspace')).toHaveCount(0);
 await expect(page.getByRole('heading', { name: 'Solicite seu atendimento' })).toBeVisible();
 await page.locator('.catalogue-service').filter({ hasText: 'Troca de correia' }).getByRole('button', { name: 'Adicionar Troca de correia' }).click();
 await page.locator('.catalogue-service').filter({ hasText: 'Troca de óleo' }).getByRole('button', { name: 'Adicionar Troca de óleo' }).click();
 await expect(page.locator('.catalogue-request .request-total strong')).toHaveText('R$ 470,00');
 await page.locator('.request-diagnostic').click();
 await expect(page.locator('.catalogue-request .request-total strong')).toHaveText('R$ 620,00');
 await page.locator('input[name="requestName"]').fill(name);
 await page.locator('input[name="requestPhone"]').fill('(14) 99999-0000');
 await page.locator('input[name="requestVehicle"]').fill('Volkswagen Polo 2021');
 await page.locator('input[name="requestPlate"]').fill('ABC1D23');
 await page.locator('select[name="preferredPeriod"]').selectOption('tarde');
 await page.getByRole('button', { name: 'Enviar solicitação' }).click();
 await expect(page.getByRole('alert')).toContainText('Descreva o problema');
 await page.locator('textarea[name="requestSymptoms"]').fill(symptoms);
 await page.setViewportSize({ width: 375, height: 850 });
 const dimensions = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }));
 assert(dimensions.scroll <= dimensions.width, 'Estouro horizontal no celular: ' + JSON.stringify(dimensions));
 await page.screenshot({ path: resolve(output, 'form-mobile.png'), fullPage: true });
 await page.setViewportSize({ width: 1280, height: 900 });
 await page.screenshot({ path: resolve(output, 'form-desktop.png'), fullPage: true });
 await page.locator('[data-theme-toggle]').click();
 await page.screenshot({ path: resolve(output, 'form-dark.png'), fullPage: true });
 const submitted = page.waitForResponse(response => response.url().endsWith('/api/public/service-requests') && response.request().method() === 'POST');
 await page.getByRole('button', { name: 'Enviar solicitação' }).click();
 const response = await submitted;
 assert.equal(response.status(), 201, await response.text());
 const request = await response.json();
 assert.equal(request.status, 'pendente');
 assert.equal(request.total, 620);
 await expect(page.getByRole('heading', { name: 'Solicitação enviada.' })).toBeVisible();
 await expect(page.locator('.request-success')).toContainText('#' + request.id);
 await page.goto(base + '/entrar');
 await page.getByLabel('E-mail', { exact: true }).fill('gerente@oscar.local');
 await page.getByLabel('Senha', { exact: true }).fill('Oscar@2026!');
 await page.getByRole('button', { name: 'Entrar', exact: true }).click();
 await expect(page).toHaveURL(/\/painel$/);
 await page.goto(base + '/solicitacoes');
 await expect(page.getByRole('heading', { name: 'Solicitações de atendimento' })).toBeVisible();
 await page.locator('.request-row').filter({ hasText: name }).click();
 await expect(page.locator('#request-detail')).toContainText(symptoms);
 await expect(page.locator('#request-detail')).toContainText('R$ 620,00');
 await expect(page.locator('#request-detail')).toContainText('Tarde');
 await page.getByRole('button', { name: 'Marcar em contato' }).click();
 await expect(page.locator('#request-detail .status-pill')).toContainText('Em contato');
 await page.screenshot({ path: resolve(output, 'fila-equipe.png'), fullPage: true });
 assert.equal(errors.length, 0, 'Erros no navegador: ' + errors.join('; '));
 console.log('PASS: CTA, seleção múltipla, total, diagnóstico obrigatório, pedido pendente e fila interna. Evidências: ' + output);
} finally {
 await browser.close();
}