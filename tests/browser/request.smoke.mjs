import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { chromium, expect } from '@playwright/test';

const base = process.env.OSCAR_BASE_URL || 'https://localhost:4201';
if (!['localhost', '127.0.0.1', '[::1]'].includes(new URL(base).hostname)) throw new Error('Teste somente no localhost.');
const executablePath = process.env.OSCAR_BROWSER || process.env.LOCALAPPDATA + '/ms-playwright/chromium-1243/chrome-win64/chrome.exe';
const browser = await chromium.launch({ headless: true, ...(existsSync(executablePath) ? { executablePath } : {}) });
const context = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const output = resolve('tests/results/request-' + Date.now());
await mkdir(output, { recursive: true });
const name = 'Cliente Teste Solicitação';
const symptoms = 'Motor perde potência e acende luz de injeção ao acelerar.';
try {
 await page.goto(base + '/catalogo');
 await expect(page.getByRole('heading', { name: 'Serviços da oficina' })).toBeVisible();
 await page.getByRole('navigation', { name: 'Navegação do catálogo' }).getByRole('link', { name: 'Serviços' }).click();
 await expect(page).toHaveURL(/\/catalogo#servicos$/);
 await page.locator('.hero-scheduling').click();
 await expect(page).toHaveURL(/#solicitar-atendimento$/);
 await expect(page.locator('.workspace')).toHaveCount(0);
 await expect(page.getByRole('heading', { name: 'Solicite seu atendimento' })).toBeVisible();
 await page.locator('.catalogue-service').filter({ hasText: 'Troca de correia' }).getByRole('button', { name: 'Adicionar Troca de correia' }).click();
 await page.locator('.catalogue-service').filter({ hasText: 'Troca de óleo' }).getByRole('button', { name: 'Adicionar Troca de óleo' }).click();
 await expect(page.locator('.catalogue-request .request-total strong')).toHaveText('R$ 470,00');
 await page.locator('.request-diagnostic').click();
 await expect(page.locator('.catalogue-request .request-total strong')).toHaveText('R$ 620,00');
 await page.locator('input[name="requestName"]').fill(name);
 await page.locator('input[name="requestPhone"]').fill('(14) 99999-0000');
 await page.locator('input[name="requestVehicle"]').fill('Volkswagen Polo 2021');
 await page.locator('input[name="requestPlate"]').fill('XYZ9A21');
 await page.locator('select[name="preferredPeriod"]').selectOption('tarde');
 await page.getByRole('button', { name: 'Enviar solicitação' }).click();
 await expect(page.getByRole('alert')).toContainText('Descreva o problema');
 await page.locator('textarea[name="requestSymptoms"]').fill(symptoms);
 await page.setViewportSize({ width: 375, height: 850 });
 const dimensions = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }));
 assert(dimensions.scroll <= dimensions.width, 'Estouro horizontal no celular: ' + JSON.stringify(dimensions));
 await page.screenshot({ path: resolve(output, 'form-mobile.png'), fullPage: true });
 await page.setViewportSize({ width: 1280, height: 900 });
 await page.screenshot({ path: resolve(output, 'form-desktop.png'), fullPage: true });
 await page.locator('[data-theme-toggle]').click();
 await page.screenshot({ path: resolve(output, 'form-dark.png'), fullPage: true });
 const submitted = page.waitForResponse(response => response.url().endsWith('/api/public/service-requests') && response.request().method() === 'POST');
 await page.getByRole('button', { name: 'Enviar solicitação' }).click();
 const response = await submitted;
 assert.equal(response.status(), 201, await response.text());
 const request = await response.json();
 assert.equal(request.status, 'pendente');
 assert.equal(request.total, 620);
 await expect(page.getByRole('heading', { name: 'Solicitação enviada.' })).toBeVisible();
 await expect(page.locator('.request-success')).toContainText('#' + request.id);
 await page.goto(base + '/entrar');
 await page.getByLabel('E-mail', { exact: true }).fill('gerente@oscar.local');
 await page.getByLabel('Senha', { exact: true }).fill('Oscar@2026!');
 await page.getByRole('button', { name: 'Entrar', exact: true }).click();
 await expect(page).toHaveURL(/\/painel$/);
 const incomingCard = page.locator('.incoming-card').filter({ hasText: name });
 await expect(incomingCard).toContainText(symptoms);
 await expect(incomingCard).toContainText('Avaliação / diagnóstico');
 await expect(page.locator('.sidebar nav a[href="/solicitacoes"] .nav-count')).toBeVisible();
 await incomingCard.getByRole('link', { name: 'Abrir solicitação ' + request.id }).click();
 await expect(page).toHaveURL(new RegExp('/solicitacoes\\?pedido=' + request.id + '$'));
 await expect(page.getByRole('heading', { name: 'Solicitações de atendimento' })).toBeVisible();
 await expect(page.locator('#request-detail')).toContainText(name);
 await expect(page.locator('#request-detail')).toContainText(symptoms);
 await expect(page.locator('#request-detail')).toContainText('R$ 620,00');
 await expect(page.locator('#request-detail')).toContainText('Tarde');
 await page.getByRole('button', { name: 'Marcar em contato' }).click();
 await expect(page.locator('#request-detail .status-pill')).toContainText('Em contato');
 await expect(page.getByRole('button', { name: 'Agendar este pedido' })).toBeVisible();
 await page.screenshot({ path: resolve(output, 'fila-equipe.png'), fullPage: true });
 await page.getByRole('button', { name: 'Agendar este pedido' }).click();
 const confirmation = page.getByRole('dialog', { name: 'Agendar pedido #' + request.id });
 await expect(confirmation).toContainText(name);
 await expect(confirmation).toContainText(symptoms);
 await expect(confirmation).toContainText('Troca de correia');
 await expect(confirmation.getByText(/cadastros provisórios/i)).toBeVisible();
 await confirmation.locator('mat-dialog-content').evaluate(element => { element.scrollTop = 0; });
 await page.screenshot({ path: resolve(output, 'confirmar-pedido-topo.png') });
 const saoPauloNow = new Date(new Date().toLocaleString('en-US', { timeZone: 'America/Sao_Paulo' }));
 const appointmentDate = new Date(saoPauloNow);
 appointmentDate.setDate(appointmentDate.getDate() + 2);
 while ([0, 6].includes(appointmentDate.getDay())) appointmentDate.setDate(appointmentDate.getDate() + 1);
 const date = [appointmentDate.getFullYear(), String(appointmentDate.getMonth() + 1).padStart(2, '0'), String(appointmentDate.getDate()).padStart(2, '0')].join('-');
 const availabilityResponse = page.waitForResponse(response => response.url().includes('/api/availability?') && response.request().method() === 'GET');
 await confirmation.getByLabel('Data', { exact: true }).fill(date);
 const availability = await (await availabilityResponse).json();
 assert(availability.slots?.length > 0, 'A fixture deve oferecer horário para este pedido.');
 const selectedMechanicId = availability.slots[0].mechanicId;
 await expect(confirmation.getByText('Somente horários livres são exibidos.')).toBeVisible();
 await confirmation.getByRole('combobox', { name: 'Horário e mecânico disponíveis' }).focus();
 await confirmation.getByRole('combobox', { name: 'Horário e mecânico disponíveis' }).press('Enter');
 await expect(page.getByRole('option').first()).toBeVisible();
 await page.getByRole('option').first().click();
 await confirmation.getByRole('checkbox', { name: 'Conversei com o cliente e confirmei este horário' }).check();
 await page.screenshot({ path: resolve(output, 'confirmar-pedido.png'), fullPage: true });
 const mechanicEmail = selectedMechanicId === 3 ? 'mecanico@oscar.local' : selectedMechanicId === 6 ? 'pedro@oscar.local' : null;
 assert(mechanicEmail, 'Mecânico inesperado na fixture: ' + selectedMechanicId);
 const mechanicContext = await browser.newContext({ ignoreHTTPSErrors: true, viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
 const mechanicPage = await mechanicContext.newPage();
 await mechanicPage.goto(base + '/entrar');
 await mechanicPage.getByLabel('E-mail', { exact: true }).fill(mechanicEmail);
 await mechanicPage.getByLabel('Senha', { exact: true }).fill('Oscar@2026!');
 await mechanicPage.getByRole('button', { name: 'Entrar', exact: true }).click();
 await expect(mechanicPage).toHaveURL(/\/painel$/);
 const confirmed = page.waitForResponse(response => response.url().endsWith('/api/service-requests/' + request.id + '/confirm') && response.request().method() === 'POST');
 await confirmation.getByRole('button', { name: 'Confirmar agendamento' }).click();
 const confirmationResponse = await confirmed;
 assert.equal(confirmationResponse.status(), 201, await confirmationResponse.text());
 const confirmationResult = await confirmationResponse.json();
 assert.equal(confirmationResult.request.appointmentId, confirmationResult.appointment.id);
 assert.equal(confirmationResult.client.registrationStatus, 'provisorio');
 assert.equal(confirmationResult.vehicle.registrationStatus, 'provisorio');
 await mechanicPage.bringToFront();
 assert.equal(await mechanicPage.evaluate(() => document.visibilityState), 'visible');
 await mechanicPage.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
 await expect(mechanicPage.getByText('Novo atendimento do pedido #' + request.id + ' atribuído a você.', { exact: false })).toBeVisible();
 await mechanicPage.goto(base + '/agenda?date=' + date + '&appointmentId=' + confirmationResult.appointment.id);
 await expect(mechanicPage.locator('.appointment-details')).toContainText(name);
 await page.bringToFront();
 await expect(page.locator('#request-detail .status-pill')).toContainText('Agendada');
 await expect(page.locator('#request-detail')).toContainText('Horário confirmado na agenda');
 await page.getByRole('link', { name: 'Ver na agenda' }).click();
 await expect(page).toHaveURL(new RegExp('/agenda\\?date=' + date + '&appointmentId=' + confirmationResult.appointment.id));
 await expect(page.locator('.appointment-details')).toContainText(name);
 await expect(page.locator('.appointment-details')).toContainText('Cadastro provisório');
 await expect(page.locator('.appointment-details')).toContainText('pedido #' + request.id);
 await page.screenshot({ path: resolve(output, 'agenda-vinculada.png'), fullPage: true });
 await page.locator('.appointment-details').getByRole('link', { name: 'Abrir O.S.' }).click();
 await expect(page).toHaveURL(new RegExp('/ordens\\?appointmentId=' + confirmationResult.appointment.id));
 const orderDialog = page.getByRole('dialog', { name: 'Abrir ordem de serviço' });
 await expect(orderDialog).toContainText('pedido #' + request.id);
 await expect(orderDialog.getByRole('combobox', { name: 'Serviços contratados' })).toHaveAttribute('aria-disabled', 'true');
 await orderDialog.getByRole('button', { name: 'Abrir ordem' }).click();
 await expect(page).toHaveURL(/\/ordens\/\d+$/);
 await expect(page.locator('.source-request-note')).toContainText(symptoms);
 await expect(page.locator('.source-request-note')).toContainText('Pedido do catálogo #' + request.id);
 await expect(page.getByRole('heading', { name: 'Serviços e avaliação' })).toBeVisible();
 await expect(page.locator('.order-identity')).not.toContainText('km');
 await page.screenshot({ path: resolve(output, 'ordem-com-relato.png'), fullPage: true });
 await page.goto(base + '/agenda?date=' + date + '&appointmentId=' + confirmationResult.appointment.id);
 await expect(page.locator('.appointment-details')).toContainText(name);
 await page.getByRole('link', { name: 'Ver cliente' }).click();
 await expect(page).toHaveURL(/\/clientes\?q=/);
 const clientCard = page.locator('[data-client-card]').filter({ hasText: name });
 await expect(clientCard).toContainText('Cadastro pendente');
 await clientCard.getByRole('button', { name: 'Completar cadastro do cliente' }).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await expect(page.getByRole('dialog').getByLabel('CPF')).toHaveValue('');
 await expect(page.getByRole('dialog').getByLabel('E-mail')).toHaveValue('');
 await page.getByRole('dialog').getByRole('button', { name: 'Cancelar' }).click();
 await page.goto(base + '/veiculos?q=XYZ9A21');
 const vehicleCard = page.locator('[data-vehicle-card]').filter({ hasText: 'XYZ9A21' });
 await expect(vehicleCard).toContainText('Cadastro pendente');
 await vehicleCard.getByRole('button', { name: 'Completar cadastro do veículo' }).click();
 await expect(page.getByRole('dialog')).toBeVisible();
 await expect(page.getByRole('dialog').getByLabel('Chassi')).toHaveValue('');
 await page.getByRole('dialog').getByRole('button', { name: 'Cancelar' }).click();
 assert.equal(errors.length, 0, 'Erros no navegador: ' + errors.join('; '));
 console.log('PASS: catálogo, pedido, confirmação, agenda e cadastros provisórios. Evidências: ' + output);
} finally {
 await browser.close();
}
