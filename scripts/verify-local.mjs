import assert from 'node:assert/strict';
import fs from 'node:fs';
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));const angular=JSON.parse(fs.readFileSync('angular.json','utf8'));
assert(pkg.private===true,'O pacote precisa estar privado.');
assert(/^\^?20\./.test(pkg.dependencies['@angular/core']));
assert(/^\^?20\./.test(pkg.dependencies['@angular/material']));
assert(angular.projects.oscar.schematics['@schematics/angular:component'].standalone===false);
assert(angular.projects.oscar.architect.build.options.inlineStyleLanguage==='scss');
assert(!angular.projects.oscar.architect.build.options.ssr);
assert(fs.existsSync('src/app/app-module.ts'));
assert(!Object.keys(pkg.scripts).some(k=>/deploy|publish|push/i.test(k)));
assert(!fs.readFileSync('src/index.html','utf8').includes('fonts.googleapis.com'));
const functionEntries=fs.readdirSync('api').filter(name=>/\.(?:mjs|js|ts)$/.test(name));
assert.deepEqual(functionEntries,['index.mjs'],'Apenas a entrada da API pode virar função Vercel.');
const ignore=fs.readFileSync('.gitignore','utf8');
for(const rule of ['/data/','.env','*.local.sql','/.vercel/'])assert(ignore.split(/\r?\n/).includes(rule),'Exclusão privada ausente: '+rule);
assert(fs.readFileSync('scripts/dev.mjs','utf8').includes("OSCAR_STORAGE:'sqlite'"),'npm start deve forçar o banco local.');
assert(fs.existsSync('supabase/migrations/202610220001_oscar_private.sql'));
console.log('Verificado: Angular20, Material20, SCSS, NgModules, semSSR e sem deploy.');
