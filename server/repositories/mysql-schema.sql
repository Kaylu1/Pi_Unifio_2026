CREATE TABLE IF NOT EXISTS clients (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 cpf VARCHAR(14) NULL UNIQUE, phone VARCHAR(30) NOT NULL, email VARCHAR(254) NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, registrationStatus VARCHAR(24) NULL, data JSON NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, clientId INT UNSIGNED NULL,
 name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE, passwordHash VARCHAR(256) NOT NULL,
 role VARCHAR(24) NOT NULL, active BOOLEAN NOT NULL DEFAULT TRUE, data JSON NOT NULL,
 FOREIGN KEY (clientId) REFERENCES clients(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS vehicles (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, clientId INT UNSIGNED NOT NULL,
 plate VARCHAR(24) NULL UNIQUE, chassis VARCHAR(30) NULL UNIQUE, brand VARCHAR(80) NULL,
 model VARCHAR(120) NOT NULL, year SMALLINT NULL, mileage INT UNSIGNED NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, registrationStatus VARCHAR(24) NULL, data JSON NOT NULL,
 FOREIGN KEY (clientId) REFERENCES clients(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS services (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL, description TEXT NULL,
 price DECIMAL(12,2) NOT NULL, durationMinutes INT UNSIGNED NOT NULL, purpose VARCHAR(24) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, data JSON NOT NULL, CHECK (price >= 0), CHECK (durationMinutes > 0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS suppliers (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(160) NOT NULL, cnpj VARCHAR(18) NULL UNIQUE,
 contact VARCHAR(254) NULL, leadDays INT UNSIGNED NOT NULL DEFAULT 0,
 active BOOLEAN NOT NULL DEFAULT TRUE, data JSON NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS parts (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, supplierId INT UNSIGNED NULL, code VARCHAR(60) NOT NULL UNIQUE,
 description VARCHAR(240) NOT NULL, unit VARCHAR(20) NOT NULL, cost DECIMAL(12,2) NOT NULL,
 price DECIMAL(12,2) NOT NULL, stock DECIMAL(14,3) NOT NULL, manualMinimum DECIMAL(14,3) NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, data JSON NOT NULL,
 FOREIGN KEY (supplierId) REFERENCES suppliers(id) ON DELETE RESTRICT,
 CHECK (cost >= 0), CHECK (price >= 0), CHECK (stock >= 0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS service_requests (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, clientId INT UNSIGNED NULL, vehicleId INT UNSIGNED NULL,
 appointmentId INT UNSIGNED NULL, name VARCHAR(120) NOT NULL, phone VARCHAR(30) NOT NULL,
 vehicle VARCHAR(160) NOT NULL, plate VARCHAR(24) NULL, symptoms TEXT NULL, status VARCHAR(40) NOT NULL,
 preferredDate DATE NULL, preferredPeriod VARCHAR(30) NULL, total DECIMAL(12,2) NOT NULL DEFAULT 0,
 durationMinutes INT UNSIGNED NOT NULL DEFAULT 0, data JSON NOT NULL,
 FOREIGN KEY (clientId) REFERENCES clients(id) ON DELETE RESTRICT,
 FOREIGN KEY (vehicleId) REFERENCES vehicles(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS appointments (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, clientId INT UNSIGNED NOT NULL, vehicleId INT UNSIGNED NOT NULL,
 mechanicId INT UNSIGNED NOT NULL, serviceRequestId INT UNSIGNED NULL, date DATE NOT NULL,
 time CHAR(5) NOT NULL, durationMinutes INT UNSIGNED NOT NULL, status VARCHAR(30) NOT NULL,
 reason TEXT NULL, data JSON NOT NULL,
 FOREIGN KEY (clientId) REFERENCES clients(id) ON DELETE RESTRICT,
 FOREIGN KEY (vehicleId) REFERENCES vehicles(id) ON DELETE RESTRICT,
 FOREIGN KEY (mechanicId) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY (serviceRequestId) REFERENCES service_requests(id) ON DELETE RESTRICT,
 INDEX idx_appointments_day_mechanic (date, mechanicId, status)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS appointment_services (
 appointmentId INT UNSIGNED NOT NULL, serviceId INT UNSIGNED NOT NULL, PRIMARY KEY (appointmentId, serviceId),
 FOREIGN KEY (appointmentId) REFERENCES appointments(id) ON DELETE CASCADE,
 FOREIGN KEY (serviceId) REFERENCES services(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS orders (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, clientId INT UNSIGNED NOT NULL, vehicleId INT UNSIGNED NOT NULL,
 mechanicId INT UNSIGNED NOT NULL, appointmentId INT UNSIGNED NULL, originOrderId INT UNSIGNED NULL,
 number INT UNSIGNED NOT NULL UNIQUE, type VARCHAR(24) NOT NULL, status VARCHAR(40) NOT NULL,
 assessmentNotes TEXT NULL, closedAt VARCHAR(32) NULL, data JSON NOT NULL,
 FOREIGN KEY (clientId) REFERENCES clients(id) ON DELETE RESTRICT,
 FOREIGN KEY (vehicleId) REFERENCES vehicles(id) ON DELETE RESTRICT,
 FOREIGN KEY (mechanicId) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY (appointmentId) REFERENCES appointments(id) ON DELETE RESTRICT,
 FOREIGN KEY (originOrderId) REFERENCES orders(id) ON DELETE RESTRICT,
 INDEX idx_orders_status_mechanic (status, mechanicId)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS order_items (
 orderId INT UNSIGNED NOT NULL, itemId VARCHAR(100) NOT NULL, section VARCHAR(16) NOT NULL,
 serviceId INT UNSIGNED NULL, partId INT UNSIGNED NULL, kind VARCHAR(20) NOT NULL,
 description VARCHAR(240) NOT NULL, quantity DECIMAL(14,3) NOT NULL, price DECIMAL(12,2) NOT NULL,
 decision VARCHAR(24) NOT NULL, data JSON NOT NULL, PRIMARY KEY (orderId, itemId, section),
 FOREIGN KEY (orderId) REFERENCES orders(id) ON DELETE CASCADE,
 FOREIGN KEY (serviceId) REFERENCES services(id) ON DELETE RESTRICT,
 FOREIGN KEY (partId) REFERENCES parts(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS budgets (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, orderId INT UNSIGNED NOT NULL, number INT UNSIGNED NOT NULL UNIQUE,
 status VARCHAR(30) NOT NULL, publishedAt VARCHAR(32) NULL, expiresAt VARCHAR(32) NULL,
 answeredAt VARCHAR(32) NULL, tokenHash VARCHAR(128) NULL, link TEXT NULL, data JSON NOT NULL,
 FOREIGN KEY (orderId) REFERENCES orders(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS movements (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, partId INT UNSIGNED NOT NULL, orderId INT UNSIGNED NULL,
 supplierId INT UNSIGNED NULL, userId INT UNSIGNED NULL, type VARCHAR(24) NOT NULL,
 quantity DECIMAL(14,3) NOT NULL, date DATE NOT NULL, notes TEXT NULL, data JSON NOT NULL,
 FOREIGN KEY (partId) REFERENCES parts(id) ON DELETE RESTRICT,
 FOREIGN KEY (orderId) REFERENCES orders(id) ON DELETE RESTRICT,
 FOREIGN KEY (supplierId) REFERENCES suppliers(id) ON DELETE RESTRICT,
 FOREIGN KEY (userId) REFERENCES users(id) ON DELETE RESTRICT,
 INDEX idx_movements_part_date (partId, date), CHECK (quantity > 0)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS tickets (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, orderId INT UNSIGNED NOT NULL, clientId INT UNSIGNED NOT NULL,
 status VARCHAR(40) NOT NULL, description TEXT NOT NULL, notes TEXT NULL, data JSON NOT NULL,
 FOREIGN KEY (orderId) REFERENCES orders(id) ON DELETE RESTRICT,
 FOREIGN KEY (clientId) REFERENCES clients(id) ON DELETE RESTRICT
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS emails (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, data JSON NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS audit (id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, data JSON NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS settings (id INT UNSIGNED PRIMARY KEY, data JSON NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sessions (
 token VARCHAR(128) PRIMARY KEY, userId INT UNSIGNED NOT NULL, csrf VARCHAR(128) NOT NULL,
 lastSeen BIGINT NOT NULL, FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS reset_tokens (
 token VARCHAR(128) PRIMARY KEY, userId INT UNSIGNED NOT NULL, expiresAt BIGINT NOT NULL,
 used BOOLEAN NOT NULL DEFAULT FALSE, FOREIGN KEY (userId) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS backups (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, day DATE NOT NULL UNIQUE,
 createdAt VARCHAR(32) NOT NULL, payload JSON NOT NULL
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS privacy_tombstones (id INT UNSIGNED PRIMARY KEY, erasedAt VARCHAR(32) NOT NULL) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS service_request_tombstones (id INT UNSIGNED PRIMARY KEY, erasedAt VARCHAR(32) NOT NULL) ENGINE=InnoDB;
